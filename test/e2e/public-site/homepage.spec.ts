import { test, expect } from '@playwright/test'
import { SOURCE_OFFER } from '../../../src/config/version'

test.describe('Homepage', () => {
  test('page loads with correct title', async ({ page }) => {
    await page.goto('/')
    await expect(page.locator('header')).toContainText('Ritual')
  })

  test('deck cards are rendered in a grid', async ({ page }) => {
    await page.goto('/')
    const deckCards = page.locator('.deck-cover')
    await expect(deckCards.first()).toBeVisible()
    expect(await deckCards.count()).toBeGreaterThan(0)
  })

  test('the footer carries the Fan Content Policy notice and the Scryfall credit', async ({
    page,
  }) => {
    await page.goto('/')
    const footer = page.locator('footer.site-footer')
    await expect(footer).toContainText('unofficial Fan Content')
    await expect(footer.getByRole('link', { name: 'Fan Content Policy' })).toHaveAttribute(
      'href',
      'https://company.wizards.com/en/legal/fancontentpolicy',
    )
    await expect(footer.getByRole('link', { name: 'Scryfall' })).toHaveAttribute(
      'href',
      'https://scryfall.com',
    )
  })

  test('the footer offers the source of the Ritual version that built the site', async ({
    page,
  }) => {
    await page.goto('/')
    const footer = page.locator('footer.site-footer')
    // global-setup builds the site with `bun run index.ts` from this checkout,
    // so the building Ritual's offer is this process's own.
    await expect(footer).toContainText(
      `Generated by ritual ${SOURCE_OFFER.version}, free software under the AGPL-3.0-only`,
    )
    await expect(footer.getByRole('link', { name: 'ritual' })).toHaveAttribute(
      'href',
      SOURCE_OFFER.sourceUrl,
    )
    await expect(footer.getByRole('link', { name: 'source code' })).toHaveAttribute(
      'href',
      SOURCE_OFFER.revisionUrl,
    )
  })

  test('collections tab shows collection cards', async ({ page }) => {
    await page.goto('#/collections')
    await expect(page.locator('h1')).toContainText('My Collections')
    const collectionCards = page.locator('.deck-cover')
    await expect(collectionCards.first()).toBeVisible()
  })
})
